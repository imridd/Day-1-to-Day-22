
import pool from '../config/database.js';
import fs from 'node:fs/promises';
import path from 'node:path';
import { randomUUID } from 'node:crypto';

const STORAGE_DIR = path.resolve(
  process.cwd(),
  'storage',
  'ticket-attachments'
);

const MAX_FILE_SIZE = 5 * 1024 * 1024;

const ALLOWED_TYPES = {
  'image/jpeg': {
    extension: '.jpg',
    check: buffer =>
      buffer.length >= 3 &&
      buffer[0] === 0xff &&
      buffer[1] === 0xd8 &&
      buffer[2] === 0xff
  },

  'image/png': {
    extension: '.png',
    check: buffer =>
      buffer.length >= 8 &&
      buffer.subarray(0, 8).equals(
        Buffer.from([
          0x89, 0x50, 0x4e, 0x47,
          0x0d, 0x0a, 0x1a, 0x0a
        ])
      )
  },

  'application/pdf': {
    extension: '.pdf',
    check: buffer =>
      buffer.length >= 5 &&
      buffer.subarray(0, 5).toString() === '%PDF-'
  }
};

const isValidId = value =>
  /^[1-9]\d*$/.test(String(value));

function sanitizeOriginalFilename(filename) {
  // Remove both Windows and Unix path components.
  const normalised = String(filename || 'attachment')
    .replace(/\\/g, '/');

  const baseName = path.posix.basename(normalised);

  const cleaned = baseName
    .replace(/[^\w. ()-]/g, '_')
    .replace(/^\.+/, '')
    .slice(0, 255);

  return cleaned || 'attachment';
}

function getSafeStoredFilename(filename) {
  // Only UUID-based filenames generated by this application are accepted.
  if (
    typeof filename !== 'string' ||
    !/^[0-9a-f-]{36}\.(jpg|png|pdf)$/i.test(filename)
  ) {
    return null;
  }

  return filename;
}

// VERIFY USER AND TICKET ACCESS
async function verifyTicketAccess(user, ticketId) {

  if (!isValidId(ticketId)) {
    return {
      allowed: false,
      statusCode: 400,
      message: 'Invalid ticket ID'
    };
  }

  if (user.role === 'Customer') {

    const customerId = Number(user.customerId);

    if (!Number.isSafeInteger(customerId) || customerId < 1) {
      return {
        allowed: false,
        statusCode: 401,
        message: 'Invalid customer account information'
      };
    }

    const [customers] = await pool.execute(
      `SELECT customer_id
       FROM customers
       WHERE customer_id = ?
       LIMIT 1`,
      [customerId]
    );

    if (customers.length === 0) {
      return {
        allowed: false,
        statusCode: 401,
        message: 'Customer account not found'
      };
    }

  } else if (
    user.role === 'Manager' ||
    user.role === 'Agent'
  ) {

    const agentId = Number(user.agentId);

    if (!Number.isSafeInteger(agentId) || agentId < 1) {
      return {
        allowed: false,
        statusCode: 401,
        message: 'Invalid staff account information'
      };
    }

    const [agents] = await pool.execute(
      `SELECT agent_id, role, is_active
       FROM agents
       WHERE agent_id = ?
       LIMIT 1`,
      [agentId]
    );

    if (
      agents.length === 0 ||
      agents[0].role !== user.role ||
      !agents[0].is_active
    ) {
      return {
        allowed: false,
        statusCode: 403,
        message: 'Staff account is inactive or invalid'
      };
    }

  } else {

    return {
      allowed: false,
      statusCode: 403,
      message: 'Access denied'
    };
  }

  const [tickets] = await pool.execute(
    `SELECT
       ticket_id,
       customer_id,
       assigned_agent_id
     FROM tickets
     WHERE ticket_id = ?
     LIMIT 1`,
    [ticketId]
  );

  if (tickets.length === 0) {
    return {
      allowed: false,
      statusCode: 404,
      message: 'Ticket not found'
    };
  }

  const ticket = tickets[0];

  if (
    user.role === 'Customer' &&
    String(ticket.customer_id) !== String(user.customerId)
  ) {
    return {
      allowed: false,
      statusCode: 403,
      message: 'You cannot access this ticket'
    };
  }

  if (
    user.role === 'Agent' &&
    String(ticket.assigned_agent_id) !== String(user.agentId)
  ) {
    return {
      allowed: false,
      statusCode: 403,
      message: 'Only the assigned Agent can access this ticket'
    };
  }

  return {
    allowed: true,
    ticket
  };
}

async function ticketAttachmentRoutes(fastify) {

  await fs.mkdir(STORAGE_DIR, {
    recursive: true
  });

  // UPLOAD ATTACHMENT
  fastify.post(
    '/:ticketId/attachments',
    {
      preHandler: [fastify.authenticate]
    },
    async (request, reply) => {

      const { ticketId } = request.params;

      if (!isValidId(ticketId)) {
        return reply.code(400).send({
          success: false,
          message: 'Invalid ticket ID'
        });
      }

      try {
        const access = await verifyTicketAccess(
          request.user,
          ticketId
        );

        if (!access.allowed) {
          return reply.code(access.statusCode).send({
            success: false,
            message: access.message
          });
        }

        let file;

        try {
          file = await request.file({
            limits: {
              fileSize: MAX_FILE_SIZE,
              files: 1
            }
          });
        } catch (error) {
          if (
            error.code === 'FST_REQ_FILE_TOO_LARGE' ||
            error.code === 'FST_FILES_LIMIT'
          ) {
            return reply.code(413).send({
              success: false,
              message: 'Only one file up to 5 MB is allowed'
            });
          }

          throw error;
        }

        if (!file) {
          return reply.code(400).send({
            success: false,
            message: 'Please select a file'
          });
        }

        const mimeType = file.mimetype;
        const fileType = ALLOWED_TYPES[mimeType];

        if (!fileType) {
          // Consume the stream before returning.
          file.file.resume();

          return reply.code(415).send({
            success: false,
            message: 'Only JPEG, PNG and PDF files are allowed'
          });
        }

        let buffer;

        try {
          buffer = await file.toBuffer();
        } catch (error) {
          if (error.code === 'FST_REQ_FILE_TOO_LARGE') {
            return reply.code(413).send({
              success: false,
              message: 'File size cannot exceed 5 MB'
            });
          }

          throw error;
        }

        if (file.file.truncated || buffer.length > MAX_FILE_SIZE) {
          return reply.code(413).send({
            success: false,
            message: 'File size cannot exceed 5 MB'
          });
        }

        if (buffer.length === 0) {
          return reply.code(400).send({
            success: false,
            message: 'Empty files are not allowed'
          });
        }

        if (!fileType.check(buffer)) {
          return reply.code(415).send({
            success: false,
            message: 'File content does not match its declared type'
          });
        }

        const storedFilename =
          `${randomUUID()}${fileType.extension}`;

        const originalFilename =
          sanitizeOriginalFilename(file.filename);

        const filePath = path.join(
          STORAGE_DIR,
          storedFilename
        );

        let fileSaved = false;

        try {
          await fs.writeFile(filePath, buffer, {
            flag: 'wx'
          });

          fileSaved = true;

          const customerId =
            request.user.role === 'Customer'
              ? Number(request.user.customerId)
              : null;

          const agentId =
            request.user.role === 'Customer'
              ? null
              : Number(request.user.agentId);

          const [result] = await pool.execute(
            `INSERT INTO ticket_attachments (
               ticket_id,
               uploaded_by_customer_id,
               uploaded_by_agent_id,
               original_filename,
               stored_filename,
               mime_type,
               file_size
             )
             VALUES (?, ?, ?, ?, ?, ?, ?)`,
            [
              ticketId,
              customerId,
              agentId,
              originalFilename,
              storedFilename,
              mimeType,
              buffer.length
            ]
          );

          return reply.code(201).send({
            success: true,
            message: 'Attachment uploaded successfully',
            attachment: {
              attachment_id: String(result.insertId),
              ticket_id: String(ticketId),
              original_filename: originalFilename,
              mime_type: mimeType,
              file_size: buffer.length
            }
          });

        } catch (error) {

          if (fileSaved) {
            await fs.unlink(filePath).catch(unlinkError => {
              request.log.error(unlinkError);
            });
          }

          throw error;
        }

      } catch (error) {
        request.log.error(error);

        return reply.code(500).send({
          success: false,
          message: 'Unable to save attachment'
        });
      }
    }
  );


  // LIST TICKET ATTACHMENTS
  fastify.get(
    '/:ticketId/attachments',
    {
      preHandler: [fastify.authenticate]
    },
    async (request, reply) => {

      const { ticketId } = request.params;

      if (!isValidId(ticketId)) {
        return reply.code(400).send({
          success: false,
          message: 'Invalid ticket ID'
        });
      }

      try {
        const access = await verifyTicketAccess(
          request.user,
          ticketId
        );

        if (!access.allowed) {
          return reply.code(access.statusCode).send({
            success: false,
            message: access.message
          });
        }

        const [attachments] = await pool.execute(
          `SELECT
             a.attachment_id,
             a.ticket_id,
             a.original_filename,
             a.mime_type,
             a.file_size,
             a.created_at,

             CASE
               WHEN a.uploaded_by_customer_id IS NOT NULL
                 THEN c.full_name
               ELSE ag.full_name
             END AS uploaded_by,

             CASE
               WHEN a.uploaded_by_customer_id IS NOT NULL
                 THEN 'Customer'
               ELSE ag.role
             END AS uploader_role

           FROM ticket_attachments a

           LEFT JOIN customers c
             ON c.customer_id = a.uploaded_by_customer_id

           LEFT JOIN agents ag
             ON ag.agent_id = a.uploaded_by_agent_id

           WHERE a.ticket_id = ?

           ORDER BY a.created_at DESC, a.attachment_id DESC`,
          [ticketId]
        );

        return reply.code(200).send({
          success: true,
          count: attachments.length,
          attachments
        });

      } catch (error) {
        request.log.error(error);

        return reply.code(500).send({
          success: false,
          message: 'Unable to retrieve attachments'
        });
      }
    }
  );


  // DOWNLOAD ATTACHMENT
  fastify.get(
    '/:ticketId/attachments/:attachmentId/download',
    {
      preHandler: [fastify.authenticate]
    },
    async (request, reply) => {

      const { ticketId, attachmentId } = request.params;

      if (
        !isValidId(ticketId) ||
        !isValidId(attachmentId)
      ) {
        return reply.code(400).send({
          success: false,
          message: 'Invalid ticket or attachment ID'
        });
      }

      try {
        const access = await verifyTicketAccess(
          request.user,
          ticketId
        );

        if (!access.allowed) {
          return reply.code(access.statusCode).send({
            success: false,
            message: access.message
          });
        }

        const [attachments] = await pool.execute(
          `SELECT
             attachment_id,
             ticket_id,
             original_filename,
             stored_filename,
             mime_type,
             file_size
           FROM ticket_attachments
           WHERE attachment_id = ?
             AND ticket_id = ?
           LIMIT 1`,
          [attachmentId, ticketId]
        );

        if (attachments.length === 0) {
          return reply.code(404).send({
            success: false,
            message: 'Attachment not found'
          });
        }

        const attachment = attachments[0];

        const safeStoredFilename =
          getSafeStoredFilename(attachment.stored_filename);

        if (!safeStoredFilename) {
          request.log.error(
            `Invalid stored filename for attachment ${attachmentId}`
          );

          return reply.code(500).send({
            success: false,
            message: 'Invalid attachment storage reference'
          });
        }

        const filePath = path.join(
          STORAGE_DIR,
          safeStoredFilename
        );

        let buffer;

        try {
          buffer = await fs.readFile(filePath);
        } catch (error) {
          if (error.code === 'ENOENT') {
            request.log.error(
              `Attachment file missing: ${attachmentId}`
            );

            return reply.code(404).send({
              success: false,
              message: 'Attachment file is missing from storage'
            });
          }

          throw error;
        }

        const safeFilename = sanitizeOriginalFilename(
          attachment.original_filename
        ).replace(/["\r\n]/g, '_');

        return reply
          .code(200)
          .header('Content-Type', attachment.mime_type)
          .header('Content-Length', buffer.length)
          .header(
            'Content-Disposition',
            `attachment; filename="${safeFilename}"`
          )
          .header('X-Content-Type-Options', 'nosniff')
          .header('Cache-Control', 'private, no-store')
          .send(buffer);

      } catch (error) {
        request.log.error(error);

        return reply.code(500).send({
          success: false,
          message: 'Unable to download attachment'
        });
      }
    }
  );

}

export default ticketAttachmentRoutes;
