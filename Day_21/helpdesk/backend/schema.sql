CREATE DATABASE IF NOT EXISTS helpdesk CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE helpdesk;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 role ENUM('MANAGER','AGENT','CUSTOMER') NOT NULL, is_active BOOLEAN NOT NULL DEFAULT TRUE,
 is_online BOOLEAN NOT NULL DEFAULT FALSE, last_seen_at DATETIME NULL,
 session_token CHAR(36) NULL, session_expires_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS tickets (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, ticket_no VARCHAR(24) NOT NULL UNIQUE,
 customer_id BIGINT UNSIGNED NOT NULL, assigned_agent_id BIGINT UNSIGNED NULL, last_agent_id BIGINT UNSIGNED NULL,
 title VARCHAR(180) NOT NULL, description TEXT NOT NULL, category VARCHAR(80) NOT NULL DEFAULT 'General',
 priority ENUM('LOW','MEDIUM','HIGH','CRITICAL') NOT NULL DEFAULT 'MEDIUM',
 status ENUM('OPEN','REOPENED','IN_PROGRESS','ON_HOLD','HOLD_REQUESTED','COMPLETED','RESOLVED','CLOSED') NOT NULL DEFAULT 'OPEN',
 hold_requested_by BIGINT UNSIGNED NULL, resolved_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_ticket_customer FOREIGN KEY(customer_id) REFERENCES users(id),
 CONSTRAINT fk_ticket_agent FOREIGN KEY(assigned_agent_id) REFERENCES users(id),
 CONSTRAINT fk_ticket_last_agent FOREIGN KEY(last_agent_id) REFERENCES users(id),
 INDEX idx_ticket_status(status), INDEX idx_ticket_agent(assigned_agent_id), INDEX idx_ticket_customer(customer_id)
);
CREATE TABLE IF NOT EXISTS ticket_messages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, ticket_id BIGINT UNSIGNED NOT NULL,
 sender_id BIGINT UNSIGNED NOT NULL, message TEXT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE CASCADE,
 FOREIGN KEY(sender_id) REFERENCES users(id), INDEX idx_message_ticket(ticket_id,id)
);
CREATE TABLE IF NOT EXISTS ticket_activities (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, ticket_id BIGINT UNSIGNED NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL, activity TEXT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE CASCADE, FOREIGN KEY(actor_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 ticket_id BIGINT UNSIGNED NULL, title VARCHAR(180) NOT NULL, body VARCHAR(500) NOT NULL,
 is_read BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE CASCADE
);
